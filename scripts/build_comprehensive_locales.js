// Helper to translate key if not explicitly provided
function autoTranslateKey(key, lang) {
  if (commonDict[lang] && commonDict[lang][key]) {
    return commonDict[lang][key];
  }
  let res = key;
  const subs = wordSubstitutions[lang] || [];
  for (const [regex, replacement] of subs) {
    res = res.replace(regex, replacement);
  }
  return res;
}

// Write to both src/locales/ and public/locales/
const srcLocalesDir = path.join(__dirname, '../src/locales');
const pubLocalesDir = path.join(__dirname, '../public/locales');

for (const lang of languages) {
  const srcPath = path.join(srcLocalesDir, `${lang}.json`);
  const pubPath = path.join(pubLocalesDir, `${lang}.json`);

  let currentDict = {};
  if (fs.existsSync(srcPath)) {
    try {
      currentDict = JSON.parse(fs.readFileSync(srcPath, 'utf8'));
    } catch (e) {}
  }

  // Process all keys
  let updatedCount = 0;
  for (const k of allUniqueKeys) {
    const existingVal = currentDict[k];
    // If missing or if existing value is identical to key (English fallback)
    if (!existingVal || existingVal === k) {
      const translated = autoTranslateKey(k, lang);
      currentDict[k] = translated;
      updatedCount++;
    }
  }

  const jsonStr = JSON.stringify(currentDict, null, 2);
  fs.writeFileSync(srcPath, jsonStr, 'utf8');
  fs.writeFileSync(pubPath, jsonStr, 'utf8');
  console.log(`Lang [${lang}]: Updated ${updatedCount} keys out of ${allUniqueKeys.length} total.`);
}

console.log('Finished writing all language JSON files to src/locales and public/locales!');
